// P3-06 audit generator (read-only on content). Run from the repository root:
//   node --experimental-strip-types --no-warnings --import ./docs/research/cultural/tools/ts-resolve.mjs docs/research/p3-06/tools/audit-generate.mjs
// Writes under docs/research/p3-06/: claim-ledger-<slug>.md, claim-ledger-summary.md, sources.json,
// source-integrity.md (without URL status; run url-check.sh then merge-url-status.mjs), term-index.md.
import fs from "node:fs";
const ROOT = "/Users/nidhinagumalla/Code/HinduFestivals/";
const OUT = ROOT + "docs/research/p3-06/";
const { FESTIVAL_RECORDS } = await import(ROOT + "content/index.ts");

const host = (u) => new URL(u).hostname.replace(/^www\./, "");
// Publisher "family": several pages from one publisher are NOT independent (project rule).
const family = (s) => {
  const h = host(s.url);
  if (/britannica\.com$/.test(h)) return "britannica";
  if (/hinduismtoday\.com$/.test(h)) return "hinduismtoday";
  if (/hinduamerican\.org$/.test(h)) return "haf";
  if (/brandeis\.edu$/.test(h)) return "brandeis";
  if (/incredibleindia\.gov\.in$/.test(h)) return "incredibleindia";
  if (/(vedabase\.io|krishna\.com)$/.test(h)) return "bbt";
  if (/wisdomlib\.org$/.test(h)) return "wisdomlib";
  if (/valmikiramayan\.net$/.test(h)) return "valmikiramayan";
  return h;
};
const RISK = [
  ["year", /\b(1[0-9]{3}|20[0-9]{2})\b/],
  ["number", /\b\d+(\.\d+)?\s?(days?|nights?|feet|foot|km|percent|%|dishes|modaks|sargas?)\b|\b(one and a half|twenty|thirty|forty|fifty|hundred)\b/i],
  ["named text", /\b(Purana|Ramayana|Mahabharata|Veda|Vedic|Gita|Devi Mahatmya|Upanishad|Atharvashirsha|Ramacharitmanas|Bhagavata|Valmiki|Tulsidas|Kalidasa)\b/],
  ["history", /\b(history|historians?|origin|began|ancient|century|first|oldest|revived|founded|ruled|dynasty|Peshwa|Tilak|Shivaji|Sangam)\b/i],
  ["attributed belief", /\b(said to|believed|tradition says|according to|is told|legend|myth)\b/i],
  ["prescriptive", /\b(must|should|never|always|required|do not|avoid)\b/i],
  ["health/safety", /\b(allerg|injur|safe|safety|dangerous|firecracker|fireworks|flame|candle|glass|eyes?|skin|fast(ing)?)\b/i],
  ["group claim", /\b(all|every|most|many|everyone|nobody)\s+(hindus?|families|devotees|people|communities|temples)\b/i],
];
const read = (n = "") => {
  const t = n.toLowerCase();
  const full = /read in full|read through the fetch tool|read directly/.test(t) && !/first part|first \d|first ~|partly|in part|only through a model summary|summary only/.test(t);
  const part = /first part|first \d|partly|in part|first 3,000|first ~|through the start|only in part/.test(t);
  const summary = /model summary|summary only|only as a summary|search-result summary/.test(t);
  return full ? "full" : part ? "partial" : summary ? "summary" : "unspecified";
};

const sourcesAll = []; // flat inventory
const summary = [];

for (const r of FESTIVAL_RECORDS) {
  const byId = new Map(r.sources.map((s) => [s.id, s]));
  const rows = [];
  const add = (item, kind, label, body, sourceIds, tradition) => {
    const paras = body.split(/\n\n/);
    paras.forEach((p, i) => {
      const srcs = sourceIds.map((id) => byId.get(id)).filter(Boolean);
      const fams = [...new Set(srcs.map(family))];
      const primary = srcs.some((s) => s.kind === "text");
      const flags = RISK.filter(([, re]) => re.test(p)).map(([k]) => k);
      let basis;
      if (item === "college_guide" && sourceIds.every((id) => id.startsWith("dorm-") || !byId.has(id))) basis = "PRACTICAL (no cultural claim)";
      else if (item === "college_guide") basis = fams.length >= 2 ? "PRACTICAL+MULTI" : "PRACTICAL+SINGLE";
      else if (primary && fams.length >= 2) basis = "PRIMARY+MULTI";
      else if (primary) basis = "PRIMARY";
      else if (fams.length >= 2) basis = "MULTI";
      else if (fams.length === 1) basis = "SINGLE-PUBLISHER";
      else basis = "NO SOURCE";
      const readStat = srcs.map((s) => read(s.termsNote));
      const weakRead = readStat.filter((x) => x !== "full").length;
      rows.push({ id: `${kind}${i + 1}`, label, tradition, text: p, sourceIds, fams, basis, flags, weakRead, total: srcs.length });
    });
  };
  (r.quickFacts ?? []).forEach((q, i) => add("quick_fact", `QF${i + 1}`, `Quick fact: ${q.label}`, q.text, q.sourceIds, q.tradition));
  (r.deityEntries ?? []).forEach((d, i) => add("deity", `DE${i + 1}`, `Deity: ${d.name}`, d.role, d.sourceIds, d.tradition));
  r.sections.forEach((s, i) => add(s.kind, `S${String(i + 1).padStart(2, "0")}-`, `${s.title} (${s.kind})`, s.body, s.sourceIds, s.tradition));
  // fix ids: label + paragraph number
  const counts = {};
  rows.forEach((x) => { counts[x.id] = 0; });
  let md = `# Claim ledger: ${r.name}\n\nGenerated by \`tools/audit-generate.mjs\` from \`content/festivals/${r.slug}.ts\` (read-only). **Basis** is computed from the cited sources: *PRIMARY* (a primary text among them), *MULTI* (two or more independent publisher families; several pages from one publisher count once), *SINGLE-PUBLISHER*, *PRACTICAL* (student guidance, not a cultural claim). **Flags** mark paragraphs that need extra care (dates and numbers, named texts, history, attributed beliefs, prescriptive or safety wording, group claims). **Read status** counts cited sources whose audit note does not record a full read. The auditor's decisions are in the findings register, not here; nothing in this ledger changes content.\n\n| ID | Item | Text | Sources | Basis | Flags | Sources not fully read |\n|---|---|---|---|---|---|---|\n`;
  rows.forEach((x, idx) => {
    md += `| ${r.slug.slice(0, 3).toUpperCase()}-${String(idx + 1).padStart(3, "0")} | ${x.label}${x.tradition ? ` _(${x.tradition})_` : ""} | ${x.text.replace(/\|/g, "/").replace(/\n/g, " ")} | ${x.sourceIds.join(", ")} | ${x.basis} | ${x.flags.join(", ") || "-"} | ${x.weakRead}/${x.total} |\n`;
  });
  fs.writeFileSync(OUT + `claim-ledger-${r.slug}.md`, md);
  const tally = (f) => rows.filter(f).length;
  summary.push({
    slug: r.slug, name: r.name, paragraphs: rows.length,
    primary: tally((x) => x.basis.startsWith("PRIMARY")), multi: tally((x) => x.basis === "MULTI"), single: tally((x) => x.basis === "SINGLE-PUBLISHER"),
    practical: tally((x) => x.basis.startsWith("PRACTICAL")), none: tally((x) => x.basis === "NO SOURCE"), flagged: tally((x) => x.flags.length >= 2),
    singleRows: rows.filter((x) => x.basis === "SINGLE-PUBLISHER").map((x) => `${x.label}: ${x.text.slice(0, 110)}… [${x.sourceIds.join(", ")}]`),
    sources: r.sources.length, sections: r.sections.length, qf: (r.quickFacts ?? []).length, deities: (r.deityEntries ?? []).length,
  });
  for (const s of r.sources) sourcesAll.push({ guide: r.slug, ...s, family: family(s), read: read(s.termsNote), usedBy: [...r.sections, ...(r.quickFacts ?? []), ...(r.deityEntries ?? [])].filter((x) => x.sourceIds.includes(s.id)).length });
}

// ---------------- summary
let sm = `# Claim ledger summary (P3-06)\n\nOne ledger per guide, linked in the table. Paragraph-level rows (a guide's sections, quick facts and deity entries split at blank lines).\n\n| Guide | Sections | Quick facts | Deities | Paragraph rows | PRIMARY | MULTI | SINGLE-PUBLISHER | PRACTICAL | NO SOURCE | Flagged (2+ flags) | Sources |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const s of summary) sm += `| [${s.name}](claim-ledger-${s.slug}.md) | ${s.sections} | ${s.qf} | ${s.deities} | ${s.paragraphs} | ${s.primary} | ${s.multi} | ${s.single} | ${s.practical} | ${s.none} | ${s.flagged} | ${s.sources} |\n`;
sm += `\n## Single-publisher paragraphs (each needs a conscious acceptance)\n`;
for (const s of summary) sm += `\n### ${s.name}\n${s.singleRows.map((x) => `- ${x}`).join("\n") || "- None."}\n`;
fs.writeFileSync(OUT + "claim-ledger-summary.md", sm);

// ---------------- sources.json for the URL checker
fs.writeFileSync(OUT + "sources.json", JSON.stringify(sourcesAll.map((s) => ({ guide: s.guide, id: s.id, url: s.url, publisher: s.publisher, kind: s.kind, termsChecked: s.termsChecked, read: s.read, usedBy: s.usedBy, family: s.family, accessedAt: s.accessedAt })), null, 1));

// ---------------- term index (cross-festival consistency)
const TERMS = [
  ["Rama", /\bRama\b/g], ["Ravana", /\bRavana\b/g], ["Sita", /\bSita\b/g], ["Hanuman", /\bHanuman\b/g], ["Ayodhya", /\bAyodhya\b/g],
  ["Krishna", /\bKrishna\b/g], ["Radha", /\bRadha\b/g], ["Vishnu", /\bVishnu\b/g], ["Shiva", /\bShiva\b/g], ["Parvati", /\bParvati\b/g], ["Ganesha", /\bGanesha\b/g],
  ["Durga", /\bDurga\b/g], ["Mahishasura", /\bMahishasura\b/g], ["Lakshmi", /\bLakshmi\b/g], ["Saraswati", /\bSaraswati\b/g], ["Surya", /\bSurya\b/g], ["Indra", /\bIndra\b/g],
  ["Navaratri/Navratri", /\bNava?ratri\b/g], ["Vijayadashami", /\bVijayadashami\b/g], ["Dussehra", /\bDussehra\b/g], ["Dasara", /\bDasara\b/g], ["Diwali", /\bDiwali\b/g],
  ["Shivaratri (any spelling)", /\bShiv?aratri\b|\bShivratri\b/g], ["Sankranti", /\bSankranti\b/g], ["Pongal", /\bPongal\b/g], ["Holika", /\bHolika\b/g], ["Mathura", /\bMathura\b/g],
  ["Britannica says/notes", /Britannica (says|notes|explains|credits|adds)/g], ["Hinduism Today/HAF/Brandeis attributions", /\b(Hinduism Today|HAF|Hindu American Foundation|Brandeis)\b/g],
];
const text = (r) => [r.subtitle, ...r.sections.flatMap((s) => [s.title, s.body]), ...(r.quickFacts ?? []).map((q) => q.text), ...(r.deityEntries ?? []).flatMap((d) => [d.role, d.tradition])].join("\n");
let ti = `# Term index across the ten guides (P3-06)\n\nCounts of key terms in each guide's public text (subtitle, sections, quick facts, deity entries). Used to target the consistency review; it is not itself a finding.\n\n| Term | ${FESTIVAL_RECORDS.map((r) => r.name).join(" | ")} |\n|---|${FESTIVAL_RECORDS.map(() => "---").join("|")}|\n`;
for (const [name, re] of TERMS) ti += `| ${name} | ${FESTIVAL_RECORDS.map((r) => (text(r).match(re) ?? []).length || "").join(" | ")} |\n`;
// repeated boilerplate sentences
const sentences = new Map();
for (const r of FESTIVAL_RECORDS) for (const s of text(r).split(/(?<=[.!?])\s+/)) { const k = s.trim(); if (k.length > 30) { if (!sentences.has(k)) sentences.set(k, new Set()); sentences.get(k).add(r.slug); } }
const repeated = [...sentences.entries()].filter(([, v]) => v.size >= 2).sort((a, b) => b[1].size - a[1].size);
ti += `\n## Sentences that appear in two or more guides (boilerplate check)\n\n${repeated.map(([k, v]) => `- (${v.size}) ${k}  \n  _${[...v].join(", ")}_`).join("\n") || "- None."}\n`;
// fasting / food / dorm wording
ti += `\n## Fasting wording by guide\n\n`;
for (const r of FESTIVAL_RECORDS) {
  const hits = text(r).split(/(?<=[.!?])\s+/).filter((s) => /fast(s|ing)?\b|vegetarian|dietary/i.test(s));
  ti += `- **${r.name}** (${hits.length}): ${hits.map((h) => h.replace(/\s+/g, " ")).join(" / ") || "none"}\n`;
}
ti += `\n## Housing and accommodation wording by guide\n\n`;
for (const r of FESTIVAL_RECORDS) {
  const cg = r.sections.find((s) => s.kind === "college_guide");
  ti += `- **${r.name}**: ${cg ? (cg.body.match(/[^.]*(open flames?|residence|housing)[^.]*\./gi) ?? []).map((x) => x.trim()).join(" / ") || "no housing sentence" : "NO college guide"}\n`;
}
fs.writeFileSync(OUT + "term-index.md", ti);
console.log("sources:", sourcesAll.length, "unique urls:", new Set(sourcesAll.map((s) => s.url)).size, summary.map((s) => `${s.slug}:${s.paragraphs}/${s.single}`).join(" "));
